class Solution:
    def topKFrequent(self, nums: List[int], k: int) -> List[int]:
        freq = {}
        for i in range(len(nums)):
            if nums[i] in freq:
                freq[nums[i]] += 1
            else:
                freq[nums[i]] = 1
        keys = sorted(freq.keys(), key = lambda x: freq.get(x), reverse=True)
        return keys[:k]
        